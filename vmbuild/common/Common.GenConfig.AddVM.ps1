            }
        }
        "DomainMember (Server)" {}
        "DomainMember (Client)" {
            if ($OperatingSystem -like "*Server*") {
                if ($ConfigToModify.domainDefaults.DefaultClientOS) {
                    $virtualMachine.operatingSystem = $ConfigToModify.domainDefaults.DefaultClientOS
                }
                else {
                    $virtualMachine.operatingSystem = "Windows 10 Latest (64-bit)"
                }
                $virtualMachine | Add-Member -MemberType NoteProperty -Name 'useFakeWSUSServer' -Value $false -force
            }
            else {
                $virtualMachine.operatingSystem = $OperatingSystem
            }

            $users = get-list2 -DeployConfig $oldConfig | Where-Object { $_.domainUser } | Select-Object -ExpandProperty domainUser -Unique
            [int]$i = 1
            $userPrefix = "$($oldConfig.vmOptions.prefix)".ToLower() + "user"
            $userNoPrefix = "user"
            while ($true) {
                $preferredUserName = $userPrefix + $i
                $noPrefixUserName = $userNoPrefix + $i
                if ($users -contains $preferredUserName -or $users -contains $noPrefixUserName) {
                    write-log -verbose "$preferredUserName already exists Trying next"
                    $i++
                }
                else {
                    $virtualMachine | Add-Member -MemberType NoteProperty -Name 'domainUser' -Value $noPrefixUserName -force
                    break
                }

            }

            $virtualMachine.Memory = "2GB"
            if ($virtualMachine.operatingSystem.Contains("Windows 11") ) {
                $virtualMachine.Memory = "4GB"
            }
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'installOffice' -Value $false -force
        }
        "OSDClient" {
            $virtualMachine.memory = "2GB"
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'vmGeneration' -Value "2" -force
            $virtualMachine.PsObject.Members.Remove('operatingSystem')
        }
        "SiteSystem" {
            $virtualMachine.memory = "4GB"
            $disk = [PSCustomObject]@{"E" = "250GB" }
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'additionalDisks' -Value $disk -force
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'InstallDP' -Value $true -force
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'InstallMP' -Value (-not $DistributionPointOnly) -force
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'InstallSUP' -Value $false -force
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'InstallRP' -Value $false -force
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'InstallSMSProv' -Value $false -force
            if (-not $SiteCode) {
                $SiteCode = ($ConfigToModify.virtualMachines | Where-Object { $_.Role -eq "Primary" } | Select-Object -First 1).SiteCode
                if ($test) {
                    $virtualMachine | Add-Member -MemberType NoteProperty -Name 'siteCode' -Value $SiteCode -Force
                }
                else {
                    #This sets the virtualmachine.Sitecode property.. Make sure to read this back in when done.
                    Get-SiteCodeMenu -property $virtualMachine -name "siteCode" -CurrentValue $SiteCode -ConfigToCheck $configToModify -test:$false
                }

                if (-not $($virtualMachine.SiteCode)) {
                    Write-RedX "Could not add SiteCode to SiteSystem $($virtualMachine.vmName). Cancelling"
                    return
                }

                if ((get-RoleForSitecode -ConfigToCheck $ConfigToModify -siteCode $virtualMachine.siteCode) -eq "CAS") {
                    $virtualMachine | Add-Member -MemberType NoteProperty -Name 'installDP' -Value $false -force
                    $virtualMachine | Add-Member -MemberType NoteProperty -Name 'installMP' -Value $false -force
                }

                if ($virtualMachine.installDP) {
                    $virtualMachine | Add-Member -MemberType NoteProperty -Name 'enablePullDP' -Value $false
                }
            }
            else {
                $virtualMachine | Add-Member -MemberType NoteProperty -Name 'siteCode' -Value $SiteCode -Force
            }
            # Needed when expanding an existing domain
            $siteCode = $virtualMachine.siteCode
            if ((get-RoleForSitecode -ConfigToCheck $ConfigToModify -siteCode $siteCode) -eq "Secondary") {
                $virtualMachine.installMP = $false
            }
            Set-SiteSystemPropertiesForOperatingSystem -VirtualMachine $virtualMachine
            if (-not $network) {
                $network = Get-NetworkForVM -vm $virtualMachine -ConfigToModify $oldConfig -ReturnIfNotNeeded:$true
                if ($network) {
                    $virtualMachine | Add-Member -MemberType NoteProperty -Name 'network' -Value $network -force
                }
            }
        }
        "FileServer" {
            $virtualMachine.memory = "3GB"
            $disk = [PSCustomObject]@{"E" = "600GB"; "F" = "200GB" }
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'additionalDisks' -Value $disk -force
            $virtualMachine.tpmEnabled = $false
        }
        "DC" {
            $virtualMachine.memory = "4GB"
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'ForestTrust' -Value "NONE" -force
            $virtualMachine.tpmEnabled = $false
        }
        "BDC" {
            $virtualMachine.memory = "4GB"
            $virtualMachine.tpmEnabled = $false
        }
    }

    if ([string]::IsNullOrWhiteSpace($Name)) {
        if ($virtualMachine.InstallMP -or $virtualMachine.InstallDP) {
            $machineName = Get-NewMachineName -ConfigToCheck $oldConfig -vm $virtualMachine
        }
        else {
            $machineName = Get-NewMachineName -ConfigToCheck $oldConfig -vm $virtualMachine
        }
        Write-Verbose "Machine Name Generated $machineName"
    }
    else {
        $machineName = $Name
    }
    $virtualMachine.vmName = $machineName

    if ($null -eq $ConfigToModify.VirtualMachines) {
        $ConfigToModify | Add-Member -MemberType NoteProperty -Name "VirtualMachines" -Value @() -Force
    }

    # Add BitLocker property if BLM is enabled and VM has TPM + client OS.
    # Non-domain roles (InternetClient, WorkgroupMember, AADClient) never receive BLM policy.
    if ($virtualMachine.tpmEnabled -and $ConfigToModify.cmOptions -and $ConfigToModify.cmOptions.EnableBLM -and $role -notin 'InternetClient', 'WorkgroupMember', 'AADClient') {
        $isClientOS = $virtualMachine.operatingSystem -and $virtualMachine.operatingSystem -like "Windows 1*"
        $virtualMachine | Add-Member -MemberType NoteProperty -Name "BitLocker" -Value ([bool]$isClientOS) -Force
    }

    # Add pushClient property for DomainMember and site system VMs.
    # Default from domainDefaults:
    #   client OS DomainMember        -> PushCMClientToClients
    #   server OS DomainMember (+SQL) -> PushCMClientToServers
    #   site system roles             -> PushCMClientToSiteSystems
    # Use the normalized role ($actualRoleName) here, NOT the raw $Role: the
    # role menu passes "DomainMember (Client)" / "DomainMember (Server)" /
    # "SqlServer", all of which normalize to "DomainMember". Gating on the raw
    # $Role silently skipped pushClient for every client (the "(Client)" suffix
    # made '$role -eq DomainMember' false), so the property never appeared.
    $siteSystemRoles = @('Primary', 'CAS', 'Secondary', 'SiteSystem', 'PassiveSite')
    if ($actualRoleName -eq 'DomainMember' -or $actualRoleName -in $siteSystemRoles) {
        # Canonical per-role fallback matching Get-NewDomainDefaults
        # (NewDomain.ps1): Clients ON, Servers OFF, SiteSystems OFF. Site
        # servers install the CM client locally during CM setup, so they are
        # NOT a client-push target by default (a $true fallback here wrongly
        # turned pushClient ON for site servers on domains whose domainDefaults
        # predates the PushCMClientToSiteSystems key).
        if ($actualRoleName -in $siteSystemRoles) {
            $defaultKey = 'PushCMClientToSiteSystems'
            $defaultVal = $false
        }
        else {
            $isClientOS = $virtualMachine.operatingSystem -and $virtualMachine.operatingSystem -like "Windows 1*"
            if ($isClientOS) { $defaultKey = 'PushCMClientToClients'; $defaultVal = $true }
            else { $defaultKey = 'PushCMClientToServers'; $defaultVal = $false }
        }
        if ($ConfigToModify.domainDefaults -and ($null -ne $ConfigToModify.domainDefaults.$defaultKey)) {
            $defaultVal = [bool]$ConfigToModify.domainDefaults.$defaultKey
        }
        # pushClient stores a TARGET SITE CODE string (or $false). Resolve the
        # boolean default to a concrete site code (the site whose subnet matches
        # this VM, else the first Primary) so the new VM is consistent with the
        # site-code model. Falls back to $false / the boolean when no CM site
        # exists yet.
        $pushValue = $defaultVal
        if ($defaultVal) {
            $domForPush = $null
            if ($ConfigToModify.vmOptions) { $domForPush = $ConfigToModify.vmOptions.domainName }
            $eligiblePush = @(Get-EligiblePushSites -Config $ConfigToModify -Domain $domForPush)
            if ($eligiblePush.Count -gt 0) {
                $resolved = Resolve-PushClientSite -VM $virtualMachine -Config $ConfigToModify -Domain $domForPush -EligibleSites $eligiblePush
                if ($resolved) { $pushValue = $resolved } else { $pushValue = $false }
            }
        }
        $virtualMachine | Add-Member -MemberType NoteProperty -Name "pushClient" -Value $pushValue -Force
    }

    # Add useProxy property for VMs that can sensibly route through the
    # domain's Squid proxy. Excludes the Proxy VM itself, DCs (DNS for the
    # domain itself), and StandaloneRootCA (offline, no networking). Both
    # Windows and Linux VMs are eligible -- Windows clients are configured
    # via Set-WindowsClientProxy over PSDirect, Linux clients via the Phase 3
    # roles/proxy-client bash module over SSH.
    # Default is seeded from one of two domainDefaults keys depending on the
    # VM's purpose:
    #   ConfigMgr site-system roles -> UseProxyForCM
    #   everything else (clients, plain DomainMembers, Linux) -> UseProxyForClients
    $proxyExcluded = @('Proxy', 'DC', 'BDC', 'StandaloneRootCA')
    if ($role -notin $proxyExcluded) {
        $cmRoles = @('CAS', 'Primary', 'Secondary', 'SiteSystem', 'PassiveSite', 'WSUS', 'SQLAO', 'FileServer')
        $useProxyKey = if ($role -in $cmRoles) { 'UseProxyForCM' } else { 'UseProxyForClients' }
        $useProxyDefault = $false
        if ($ConfigToModify.domainDefaults -and ($null -ne $ConfigToModify.domainDefaults.$useProxyKey)) {
            $useProxyDefault = [bool]$ConfigToModify.domainDefaults.$useProxyKey
        }
        $virtualMachine | Add-Member -MemberType NoteProperty -Name "useProxy" -Value $useProxyDefault -Force
    }

    # Linux VMs run with static memory (Hyper-V Dynamic Memory on Linux is
    # flaky), so dynamicMinRam is meaningless for them -- don't add it.
    if (-not (Test-VmIsLinux -Vm $virtualMachine)) {
        if ($ConfigToModify.domainDefaults.UseDynamicMemory) {
            # SQL workloads need a higher floor; ConfigMgr SQL min server memory is 4GB
            $defaultMin = if ($virtualMachine.sqlVersion) { "4GB" } else { "1GB" }
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'dynamicMinRam' -Value $defaultMin -force
        }
        else {
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'dynamicMinRam' -Value $virtualMachine.memory -force
        }
    }

    # Before adding, check if a VM with this name already exists
    $existingVM = $ConfigToModify.VirtualMachines | Where-Object { $_.vmName -eq $virtualMachine.vmName }
    if ($existingVM) {
        Write-Log -verbose "A VM with the name '$($virtualMachine.vmName)' already exists. Skipping add."
        if ($ReturnMachineName) {
            return $virtualMachine.vmName
        }
        else {
            return
        }
    }
    $ConfigToModify.virtualMachines += $virtualMachine

    if ($role -eq "Primary" -or $role -eq "CAS" -or $role -eq "PassiveSite" -or $role -eq "SiteSystem" -or $role -eq "Secondary") {
        # Post-migration shape: cmOptions live on each top-level site server VM
        # (CAS, or standalone Primary). Attach a block to the newly added VM
        # only when it is itself a top-level (CAS or Primary with no
        # parentSiteCode). When another top-level already exists in the
        # config, clone its cmOptions so the new hierarchy starts with the
        # same Version / PKI / BLM settings. Otherwise create defaults.
        # Child Primary under a CAS, SiteSystem, PassiveSite, and Secondary
        # all inherit at deploy time via New-DeployConfig rehydration.
        $isTopLevelAdd = ($role -in 'CAS', 'Primary') -and (-not $virtualMachine.parentSiteCode)
        if ($isTopLevelAdd -and -not $virtualMachine.cmOptions) {
            $existingTopLevel = $ConfigToModify.virtualMachines | Where-Object {
                $_.vmName -ne $virtualMachine.vmName -and
                $_.role -in 'CAS', 'Primary' -and -not $_.parentSiteCode -and $_.cmOptions
            } | Select-Object -First 1
            if ($existingTopLevel) {
                $newCmOptions = $existingTopLevel.cmOptions | ConvertTo-Json -Depth 5 -Compress | ConvertFrom-Json
            }
            else {
                # domainDefaults is a hint only. This is the one valid time to
                # consume it: the new top-level VM has no actual cmOptions yet.
                $latestVersion = Get-CmVersionWithHintFallback -DomainDefaults $ConfigToModify.domainDefaults -FallbackVersion (Get-CMLatestBaselineVersion)
                $newCmOptions = [PSCustomObject]@{
                    Version                   = $latestVersion
                    Install                   = $true
                    PrePopulateObjects        = $true
                    EVALVersion               = $false
                    #InstallSCP                = $true
                    OfflineSCP                = $false
                    OfflineSUP                = $false
                    UsePKI                    = $false
                    EnableBLM                 = $false
                    WsusImportBaseline        = $true
                }
            }
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'cmOptions' -Value $newCmOptions -force
        }
    }

    if ($role -eq "CAS") {
        Add-NewVMForRole -Role Primary -Domain $Domain -ConfigToModify $ConfigToModify -OperatingSystem $OperatingSystem -Quiet:$Quiet -parentSiteCode $virtualMachine.SiteCode -network:$virtualMachine.network
    }

    #if ($existingPrimary -gt 0) {
    #    ($ConfigToModify.virtualMachines | Where-Object { $_.Role -eq "Primary" } | Select-Object -First 1).parentSiteCode = ($ConfigToModify.virtualMachines | Where-Object { $_.Role -eq "CAS" } | Select-Object -First 1).siteCode
    #}

    if ($existingDPMP -eq 0) {
        if (-not $newSiteCode) {
            $newSiteCode = ($ConfigToModify.virtualMachines | Where-Object { $_.Role -eq "Primary" } | Select-Object -First 1).SiteCode
        }
        if (-not $test) {
            Write-Host "New Primary server found. Adding new DPMP for sitecode $newSiteCode"
        }
        Add-NewVMForRole -Role SiteSystem -Domain $Domain -ConfigToModify $ConfigToModify -OperatingSystem $OperatingSystem -SiteCode $newSiteCode -Quiet:$Quiet
    }
    if ($Role -eq "PassiveSite") {
        $SiteCode = $virtualMachine.SiteCode

        $primaryNode = $ConfigToModify.virtualMachines | Where-Object { $_.Role -in ("Primary", "CAS") -and $_.siteCode -eq $SiteCode }
        if ($primaryNode.Role -eq "Primary") {                 
            $DPsForSiteCode = $ConfigToModify.virtualMachines | Where-Object { $_.Role -eq "SiteSystem" -and $_.siteCode -eq $SiteCode -and $_.installDP -eq $true }
            if (-not $DPsForSiteCode) {
                Add-NewVMForRole -Role SiteSystem -Domain $Domain -ConfigToModify $ConfigToModify -OperatingSystem $OperatingSystem -SiteCode $SiteCode -Quiet:$Quiet
            }
        }
    }
    if ($Role -eq "SQLAO" -and (-not $secondSQLAO)) {
        write-host "$($virtualMachine.VmName) is the 1st SQLAO"
        $SQLAONode = Add-NewVMForRole -Role SQLAO -Domain $Domain -ConfigToModify $ConfigToModify -OperatingSystem $OperatingSystem -Name $Name2 -secondSQLAO:$true -Quiet:$Quiet -ReturnMachineName:$true -network:$network
        $virtualMachine | Add-Member -MemberType NoteProperty -Name 'OtherNode' -Value $SQLAONode -force
        if ($test -eq $false ) {
            $FSName = select-FileServerMenu -ConfigToModify $ConfigToModify -HA:$false
            if ($FSName -eq "ESCAPE") {
                Remove-VMFromConfig -vmName $virtualMachine.vmName -ConfigToModify $ConfigToModify
                Remove-VMFromConfig -vmName $SQLAONode -ConfigToModify $ConfigToModify
                return
            }
            $virtualMachine | Add-Member -MemberType NoteProperty -Name 'fileServerVM' -Value $FSName -force
        }
        #$virtualMachine | Add-Member -MemberType NoteProperty -Name 'SQLAgentAccount' -Value "SqlAgentUser"
        #$virtualMachine | Add-Member -MemberType NoteProperty -Name 'SqlServiceAccount' -Value "SqlServiceUser"
        $ClusterName = Get-NewMachineName -vm $virtualMachine -ConfigToCheck $ConfigToModify -ClusterName:$true -SkipOne:$true
        $virtualMachine | Add-Member -MemberType NoteProperty -Name 'ClusterName' -Value $ClusterName -force
        $AOName = Get-NewMachineName -vm $virtualMachine -ConfigToCheck $ConfigToModify -AOName:$true -SkipOne:$true
        $AGName = "SQL"
        if ($SiteCode) {
            $AGName = $siteCode
        }
        $virtualMachine | Add-Member -MemberType NoteProperty -Name 'AlwaysOnGroupName' -Value $($AGName + " Availability Group") -force
        $virtualMachine | Add-Member -MemberType NoteProperty -Name 'AlwaysOnListenerName' -Value $AOName -force

        $ServiceAccount = "$($ClusterName)Svc"
        $AgentAccount = "$($ClusterName)Agent"

        $virtualMachine | Add-Member -MemberType NoteProperty -Name 'SqlServiceAccount' -Value $ServiceAccount -force
        $virtualMachine | Add-Member -MemberType NoteProperty -Name 'SqlAgentAccount' -Value $AgentAccount -force

        $otherNode = $ConfigToModify.VirtualMachines | Where-Object { $_.vmName -eq $SQLAONode }
        $otherNode | Add-Member -MemberType NoteProperty -Name 'SqlServiceAccount' -Value $ServiceAccount -force
        $otherNode | Add-Member -MemberType NoteProperty -Name 'SqlAgentAccount' -Value $AgentAccount -force


    }
    if ($NewFSServer -eq $true) {
        #Get-PSCallStack | out-host
        $FSName = select-FileServerMenu -ConfigToModify $ConfigToModify -HA:$true
        if ($FSName -eq "ESCAPE") {
            Remove-VMFromConfig -vmName $virtualMachine.vmName -ConfigToModify $ConfigToModify
            return
        }
        $virtualMachine | Add-Member -MemberType NoteProperty -Name 'remoteContentLibVM' -Value $FSName
    }
    #Get-PSCallStack | out-host
    if (-not $Quiet) {
        Write-Host2 -ForegroundColor $Global:Common.Colors.GenConfigNotice "New Virtual Machine $machineName ($role) was added"
    }
    Write-verbose "[Add-NewVMForRole] Config: $ConfigToModify"
    if ($ReturnMachineName) {
        return $machineName
    }
}

function Add-OfflineRootCAVMIfMissing {
    # When pkiOptions.UseOfflineRoot is enabled but no Standalone Offline
    # Root CA exists - neither in the in-memory config nor already deployed
    # in the target domain - auto-add one so the user doesn't have to.
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $false)]
        [object] $ConfigToModify = $global:config
    )

    if (-not $ConfigToModify) { return }
    if (-not $ConfigToModify.vmOptions -or -not $ConfigToModify.vmOptions.domainName) { return }

    # Only proceed if pkiOptions.UseOfflineRoot is enabled
    $pkiOpts = $ConfigToModify.pkiOptions
    if (-not $pkiOpts -or -not $pkiOpts.UseOfflineRoot) { return }

    $existsInConfig = @($ConfigToModify.virtualMachines | Where-Object { $_.role -eq 'StandaloneRootCA' }).Count -gt 0
    if ($existsInConfig) { return }

    $domainName = $ConfigToModify.vmOptions.domainName
    try {
        $existsInDomain = @(Get-List -Type VM -DomainName $domainName -ErrorAction SilentlyContinue | Where-Object { $_.role -eq 'StandaloneRootCA' }).Count -gt 0
        if ($existsInDomain) { return }
    } catch {}

    write-log "[OfflineRootCA] pkiOptions.UseOfflineRoot enabled but no StandaloneRootCA VM found - auto-adding one to domain $domainName"
    $existingNames = @($ConfigToModify.virtualMachines | ForEach-Object { $_.vmName })
    $rootOS = if ($ConfigToModify.domainDefaults.DefaultServerOS) { $ConfigToModify.domainDefaults.DefaultServerOS } else { 'Server 2022' }
    Add-NewVMForRole -Role 'StandaloneRootCA' -Domain $domainName -ConfigToModify $ConfigToModify -OperatingSystem $rootOS -Quiet:$true | Out-Null
    # Tag the VM we just added so Remove-OfflineRootCAVMIfAutoAdded can
    # safely auto-remove it later if the user toggles UseOfflineRoot off.
    # We never tag a user-created VM, so manual additions are preserved.
    $newVM = $ConfigToModify.virtualMachines | Where-Object { $_.role -eq 'StandaloneRootCA' -and $existingNames -notcontains $_.vmName } | Select-Object -First 1
    if ($newVM) {
        $newVM | Add-Member -MemberType NoteProperty -Name '_autoAddedByOfflineRootCA' -Value $true -Force
        # Also update pkiOptions.OfflineRootCAVM if not already set
        if ($pkiOpts -and -not $pkiOpts.OfflineRootCAVM) {
            $pkiOpts.OfflineRootCAVM = $newVM.vmName
        }
        # Drop any stale validation messages referencing this newly-added VM
        # (see Add-ProxyVMIfMissing for the carryOver-staleness rationale).
        Clear-StaleValidationMessagesForVM -VmName $newVM.vmName
    }
}

function Clear-StaleValidationMessagesForVM {
    # Removes any entries from $global:GenConfigErrorMessages and
    # $global:PendingValidationErrors whose Message references the given VM
    # name. Called whenever an auto-add/auto-remove mutates the config so
    # stale messages from a previous validation pass (different config shape)
    # don't surface to the user via the carryOver mechanism in genconfig.ps1.
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string] $VmName
    )

    if (-not $VmName) { return }
    $needle = "[$VmName]"

    if ($global:GenConfigErrorMessages) {
        $kept = @($global:GenConfigErrorMessages | Where-Object { $_.Message -notlike "*$needle*" })
        if ($kept.Count -ne $global:GenConfigErrorMessages.Count) {
            Write-Log "[Clear-StaleValidationMessagesForVM] Dropped $($global:GenConfigErrorMessages.Count - $kept.Count) stale msg(s) for $VmName from GenConfigErrorMessages" -LogOnly
            $global:GenConfigErrorMessages = $kept
        }
    }
    if ($global:PendingValidationErrors) {
        $kept = @($global:PendingValidationErrors | Where-Object { $_.Message -notlike "*$needle*" })
        if ($kept.Count -ne $global:PendingValidationErrors.Count) {
            Write-Log "[Clear-StaleValidationMessagesForVM] Dropped $($global:PendingValidationErrors.Count - $kept.Count) stale msg(s) for $VmName from PendingValidationErrors" -LogOnly
            $global:PendingValidationErrors = $kept
        }
    }
}

function Remove-OfflineRootCAVMIfAutoAdded {
    # Counterpart to Add-OfflineRootCAVMIfMissing: when pkiOptions.UseOfflineRoot
    # is disabled, remove any StandaloneRootCA VM that we previously auto-added.
    # We only remove VMs tagged with _autoAddedByOfflineRootCA, so user-created
    # Root CA VMs are preserved. We also skip removal if the VM is already
    # deployed in the domain.
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $false)]
        [object] $ConfigToModify = $global:config
    )

    if (-not $ConfigToModify) { return }
    if (-not $ConfigToModify.virtualMachines) { return }

    # Only auto-remove when pkiOptions.UseOfflineRoot is disabled
    $pkiOpts = $ConfigToModify.pkiOptions
    $offlineRootEnabled = $pkiOpts -and $pkiOpts.UseOfflineRoot
    if ($offlineRootEnabled) { return }

    $domainName = if ($ConfigToModify.vmOptions) { $ConfigToModify.vmOptions.domainName } else { $null }
    $deployedNames = @()
    if ($domainName) {
        try {
            $deployedNames = @(Get-List -Type VM -DomainName $domainName -ErrorAction SilentlyContinue | ForEach-Object { $_.vmName })
        } catch {}
    }

    $toRemove = @($ConfigToModify.virtualMachines | Where-Object {
        $_.role -eq 'StandaloneRootCA' -and
        $_.PSObject.Properties['_autoAddedByOfflineRootCA'] -and
        $_._autoAddedByOfflineRootCA -and
        ($deployedNames -notcontains $_.vmName)
    })
    foreach ($vm in $toRemove) {
        write-log "[OfflineRootCA] UseOfflineRoot disabled - auto-removing previously auto-added StandaloneRootCA VM '$($vm.vmName)'"
        Remove-VMFromConfig -vmName $vm.vmName -ConfigToModify $ConfigToModify
    }
}

function Test-ConfigNeedsProxy {
    # Returns $true iff any non-hidden VM in the config has useProxy=$true.
    # domainDefaults.UseProxyFor* are seed-only hints used by Add-NewVMForRole
    # to populate the per-VM useProxy at creation time; they are NOT consulted
    # here. If every VM has useProxy=$false, the config does not need a proxy,
    # regardless of what the domain default says.
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [object] $ConfigToModify
    )

    foreach ($vm in @($ConfigToModify.virtualMachines)) {
        if ($vm.hidden) { continue }
        if ($vm.PSObject.Properties.Name -contains 'useProxy' -and [bool]$vm.useProxy) {
            return $true
        }
    }
    return $false
}

function Disable-ProxyOptIn {
    # Clears every proxy opt-in in the config so a Proxy VM the user just
    # deleted is not immediately re-added by Add-ProxyVMIfMissing on the next
    # menu pass. Returns what was flipped so the caller can report it.
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $false)]
        [object] $ConfigToModify = $global:config
    )

    $flipped = New-Object System.Collections.Generic.List[string]
    if (-not $ConfigToModify) { return $flipped.ToArray() }

    foreach ($vm in @($ConfigToModify.virtualMachines)) {
        if (-not $vm) { continue }
        if ($vm.PSObject.Properties.Name -contains 'useProxy' -and [bool]$vm.useProxy) {
            $vm.useProxy = $false
            $flipped.Add([string]$vm.vmName)
        }
    }

    # Seed-only hints: left true, the next VM added would opt in and pull a
    # replacement Proxy VM straight back into the config.
    if ($ConfigToModify.domainDefaults) {
        foreach ($key in @('UseProxyForClients', 'UseProxyForCM')) {
            if ($ConfigToModify.domainDefaults.PSObject.Properties.Name -contains $key -and [bool]$ConfigToModify.domainDefaults.$key) {
                $ConfigToModify.domainDefaults.$key = $false
                $flipped.Add("domainDefaults.$key")
            }
        }
    }

    return $flipped.ToArray()
}

function Add-ProxyVMIfMissing {
    # When the in-memory config opts into the proxy (domainDefaults.UseProxyFor*
    # or any per-VM useProxy=$true) but no Proxy VM exists -- neither in the
    # config nor already deployed in the target domain -- auto-add a Linux
    # Proxy VM so the user doesn't have to. Counterpart to
    # Remove-ProxyVMIfAutoAdded.
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $false)]
        [object] $ConfigToModify = $global:config
    )

    if (-not $ConfigToModify) { return }
    if (-not $ConfigToModify.vmOptions -or -not $ConfigToModify.vmOptions.domainName) { return }
    if (-not (Test-ConfigNeedsProxy -ConfigToModify $ConfigToModify)) { return }

    $existsInConfig = @($ConfigToModify.virtualMachines | Where-Object { $_.role -eq 'Proxy' }).Count -gt 0
    if ($existsInConfig) { return }

    $domainName = $ConfigToModify.vmOptions.domainName
    try {
        $existsInDomain = @(Get-List -Type VM -DomainName $domainName -ErrorAction SilentlyContinue | Where-Object { $_.role -eq 'Proxy' }).Count -gt 0
        if ($existsInDomain) { return }
    } catch {}

    write-log "[Proxy] Proxy is enabled (domainDefaults or per-VM useProxy) but no Proxy VM found - auto-adding one to domain $domainName"
    $existingNames = @($ConfigToModify.virtualMachines | ForEach-Object { $_.vmName })
    Add-NewVMForRole -Role 'Proxy' -Domain $domainName -ConfigToModify $ConfigToModify -Quiet:$true | Out-Null
    # Tag the VM we just added so Remove-ProxyVMIfAutoAdded can safely
    # auto-remove it later if the user disables proxy. User-created Proxy
    # VMs are never tagged, so manual additions are preserved.
    $newVM = $ConfigToModify.virtualMachines | Where-Object { $_.role -eq 'Proxy' -and $existingNames -notcontains $_.vmName } | Select-Object -First 1
    if ($newVM) {
        $newVM | Add-Member -MemberType NoteProperty -Name '_autoAddedByProxy' -Value $true -Force
        # Drop any stale validation messages that reference this newly-added
        # VM name. They can only have come from a previous validation pass
        # (different config shape) and would mislead the user.
        Clear-StaleValidationMessagesForVM -VmName $newVM.vmName
        # write-log above is wiped by the menu's clear-screen; the banner is
        # the only channel the user actually gets to read.
        $optedIn = @($ConfigToModify.virtualMachines | Where-Object { -not $_.hidden -and $_.PSObject.Properties.Name -contains 'useProxy' -and [bool]$_.useProxy } | ForEach-Object { $_.vmName })
        $because = 'the domain proxy defaults'
        if ($optedIn.Count -gt 0) { $because = "useProxy=true on $($optedIn -join ', ')" }
        Add-ErrorMessage -Warning -property 'useProxy' -message "Added Proxy VM $($newVM.vmName) to $domainName because of $because. Deleting the Proxy VM turns useProxy off everywhere."
    }
}

function Remove-ProxyVMIfAutoAdded {
    # Counterpart to Add-ProxyVMIfMissing: when nothing in the config opts
    # into the proxy any longer, remove any Proxy VM that we previously
    # auto-added. Only removes VMs tagged with _autoAddedByProxy and not
    # already deployed in the domain, so user-created Proxy VMs are preserved.
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $false)]
        [object] $ConfigToModify = $global:config
    )

    if (-not $ConfigToModify) { return }
    if (-not $ConfigToModify.virtualMachines) { return }
    if (Test-ConfigNeedsProxy -ConfigToModify $ConfigToModify) { return }

    $domainName = if ($ConfigToModify.vmOptions) { $ConfigToModify.vmOptions.domainName } else { $null }
    $deployedNames = @()
    if ($domainName) {
        try {
            $deployedNames = @(Get-List -Type VM -DomainName $domainName -ErrorAction SilentlyContinue | ForEach-Object { $_.vmName })
        } catch {}
    }

    $toRemove = @($ConfigToModify.virtualMachines | Where-Object {
        $_.role -eq 'Proxy' -and
        $_.PSObject.Properties['_autoAddedByProxy'] -and
        $_._autoAddedByProxy -and
        ($deployedNames -notcontains $_.vmName)
    })
    foreach ($vm in $toRemove) {
        write-log "[Proxy] Proxy no longer enabled - auto-removing previously auto-added Proxy VM '$($vm.vmName)'"
        Remove-VMFromConfig -vmName $vm.vmName -ConfigToModify $ConfigToModify
    }
}
