# This file must be saved with UTF-8 BOM. createGuestDscZip.ps1 loads it under PS 5.1, which needs the BOM to parse Unicode.
function Rename-VirtualMachine {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true, HelpMessage = "Base Property Object")]
        [Object] $vm,
        [Parameter(Mandatory = $false, HelpMessage = "NewName - AutoGenerated if blank")]
        [string] $newName
    )

    if ($vm.ExistingVM) {
        return
    }
    $rename = $true
    if (-not $newName) {
        $rename = $false
        $newName = Get-NewMachineName -vm $vm
        if ($($vm.vmName) -ne $newName) {
            $rename = $true
            Write-Log -Activity "Proposing to rename $($vm.vmName) to $($newName) due to configuration changes" -NoNewLine
            $response = Read-YesOrNoWithTimeout -Prompt "Rename $($vm.vmName) to $($newName)? (Y/n)" -HideHelp -Default "y"
            if (-not [String]::IsNullOrWhiteSpace($response)) {
                if ($response.ToLowerInvariant() -eq "n" -or $response.ToLowerInvariant() -eq "no") {
                    $rename = $false
                }
            }
        }
    }

    if ($rename -eq $true) {

        foreach ($existing in $Global:Config.virtualMachines) {
            if ($existing.RemoteSQLVM -eq $vm.vmName) {
                $existing.RemoteSQLVM = $newName
            }
            if ($existing.remoteContentLibVM -eq $vm.vmName) {
                $existing.remoteContentLibVM = $newName
            }
            if ($existing.patchMyPCFileServer -eq $vm.vmName) {
                $existing.patchMyPCFileServer = $newName
            }
            if ($existing.FileServerVM -eq $vm.vmName) {
                $existing.FileServerVM = $newName
            }
            if ($existing.pullDPSourceDP -eq $vm.vmName) {
                $existing.pullDPSourceDP = $newName
            }
            if ($existing.wsusDataBaseServer -eq $vm.vmName) {
                $existing.wsusDataBaseServer = $newName
            }


        }
        $vm.vmName = $newName
        return $newName
    }

}

function Test-OsdNetworkHasDistributionPoint {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [string] $Network,
        [Parameter(Mandatory = $true)]
        [object] $Config
    )

    $allVMs = @(Get-List2 -DeployConfig $Config)
    $allVMs += @($Config.virtualMachines | Where-Object { $null -ne $_ })
    if ($global:existingMachines) {
        $allVMs += @($global:existingMachines | Where-Object { $null -ne $_ })
    }

    foreach ($candidate in $allVMs) {
        if (($candidate.installDP -eq $true -or $candidate.enablePullDP -eq $true) -and
            (Get-OsdEffectiveNetwork -VM $candidate -Config $Config) -eq $Network) {
            return $true
        }
    }
    return $false
}

function Get-OsdPxePathsForNetwork {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)] [string] $Network,
        [Parameter(Mandatory = $true)] [object] $Config
    )

    # The VM being edited is not guaranteed to have been appended to the
    # config yet. Add a transient client so the shared resolver can judge the
    # proposed network without mutating authored state.
    $probeConfig = $Config | ConvertTo-Json -Depth 8 | ConvertFrom-Json
    if (-not ($probeConfig.virtualMachines | Where-Object {
                $_.role -eq 'OSDClient' -and (Get-OsdEffectiveNetwork -VM $_ -Config $probeConfig) -eq $Network
            })) {
        $probeConfig.virtualMachines += [pscustomobject]@{
            vmName = '__OSD_NETWORK_PROBE__'
            role = 'OSDClient'
            network = $Network
        }
    }
    $inventory = @(Get-List2 -DeployConfig $Config)
    $inventory += @($Config.virtualMachines | Where-Object { $_.hidden })
    if ($global:existingMachines) { $inventory += @($global:existingMachines) }
    $inventory += @($probeConfig.virtualMachines)
    return @(Get-OsdPxePaths -Config $probeConfig -Inventory $inventory | Where-Object {
            $_.clientNetwork -eq $Network
        })
}

function Get-OsdRelayDistributionPointCandidates {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)] [string] $Network,
        [Parameter(Mandatory = $true)] [object] $Config
    )

    # Existing VM notes carry LastKnownIP while hidden config entries omit it.
    # Prefer live inventory for candidate facts; config remains the fallback
    # for newly authored DPs (which normally lack a stable address until deploy).
    $allVMs = @(Get-List -Type VM -DomainName $Config.vmOptions.domainName -ErrorAction SilentlyContinue)
    if ($global:existingMachines) { $allVMs += @($global:existingMachines) }
    $allVMs += @(Get-List2 -DeployConfig $Config)
    $allVMs += @($Config.virtualMachines)
    $seen = @{}
    foreach ($candidate in $allVMs) {
        if (-not $candidate -or -not $candidate.vmName) { continue }
        $key = "$($candidate.vmName)".ToLowerInvariant()
        if ($seen.ContainsKey($key)) { continue }
        $seen[$key] = $true
        if (-not ($candidate.installDP -eq $true -or $candidate.enablePullDP -eq $true)) { continue }
        if ([string]::IsNullOrWhiteSpace("$($candidate.siteCode)")) { continue }
        $candidateNetwork = Get-OsdEffectiveNetwork -VM $candidate -Config $Config
        if ($candidateNetwork -eq $Network) { continue }

        $ipValues = @($candidate.AssignedIP, $candidate.LastKnownIP)
        if ($candidate.thisParams) {
            $ipValues += @($candidate.thisParams.AssignedIP, $candidate.thisParams.IPv4Address)
        }
        $ipValues = @($ipValues | ForEach-Object {
                $candidateIp = "$_" -replace '/\d+$', ''
                $parsedCandidateIp = $null
                if ($_ -and [System.Net.IPAddress]::TryParse($candidateIp, [ref]$parsedCandidateIp) -and
                    $parsedCandidateIp.AddressFamily -eq [System.Net.Sockets.AddressFamily]::InterNetwork) {
                    $parsedCandidateIp.IPAddressToString
                }
            } | Select-Object -Unique)
        if ($ipValues.Count -ne 1) { continue }

        [pscustomobject]@{
            VM = $candidate
            Network = "$candidateNetwork"
            SiteCode = "$($candidate.siteCode)"
            IPv4 = "$($ipValues[0])"
        }
    }
}

function Add-DhcpRelayForOsdNetwork {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)] [string] $Network,
        [Parameter(Mandatory = $true)] [object] $Config
    )

    $candidates = @(Get-OsdRelayDistributionPointCandidates -Network $Network -Config $Config)
    if ($candidates.Count -eq 0) {
        Write-RedX "No remote Distribution Point with one agreed stable IPv4 address is available."
        return $false
    }
    $candidateOptions = @($candidates | ForEach-Object {
            "$($_.VM.vmName) [site $($_.SiteCode), subnet $($_.Network), $($_.IPv4)]"
        })
    $selection = Get-Menu2 -MenuName "Relay PXE requests from $Network" `
        -Prompt 'Select the remote Distribution Point that will answer PXE' `
        -OptionArray $candidateOptions -Test:$false -Split
    if ([string]::IsNullOrWhiteSpace($selection) -or $selection -eq 'ESCAPE') { return $false }
    $target = $candidates | Where-Object { $_.VM.vmName -eq $selection } | Select-Object -First 1
    if (-not $target) { return $false }

    $originalVirtualMachines = $Config.virtualMachines | ConvertTo-Json -Depth 8 | ConvertFrom-Json
    $existingRelaySources = @($Config.virtualMachines)
    $existingRelaySources += @($global:existingMachines)
    $existingRelaySources += @(Get-List -Type VM -DomainName $Config.vmOptions.domainName -ErrorAction SilentlyContinue)
    $relays = @($existingRelaySources | Where-Object { $_.role -eq 'DHCPRelay' } |
        Group-Object -Property vmName | ForEach-Object { $_.Group | Select-Object -First 1 })
    if ($relays.Count -gt 1) {
        Write-RedX "Domain '$($Config.vmOptions.domainName)' has multiple DHCPRelay VMs: $(@($relays.vmName) -join ', ')."
        return $false
    }

    try {
        $relay = $null
        $relayIsExisting = $false
        if ($relays.Count -eq 1) {
            $relay = $relays[0] | ConvertTo-Json -Depth 8 | ConvertFrom-Json
            $relayIsExisting = [bool]($relay.hidden -or $relay.ExistingVM -or
                ($global:existingMachines | Where-Object { $_.vmName -eq $relay.vmName }))
        }
        else {
            $beforeNames = @($Config.virtualMachines | ForEach-Object { $_.vmName })
            $null = Add-NewVMForRole -Role 'DHCPRelay' -Domain $Config.vmOptions.domainName `
                -ConfigToModify $Config -Network $Config.vmOptions.network -Quiet:$true
            $relay = $Config.virtualMachines | Where-Object {
                $_.role -eq 'DHCPRelay' -and $beforeNames -notcontains $_.vmName
            } | Select-Object -First 1
            if (-not $relay) { throw 'the DHCPRelay VM was not created' }
        }

        $newMappings = @($relay.relayMappings | Where-Object {
                $null -ne $_ -and "$($_.clientNetwork)" -ne $Network
            })
        $newMappings += [pscustomobject]@{
            clientNetwork = $Network
            distributionPointVM = "$($target.VM.vmName)"
        }
        $relay | Add-Member -MemberType NoteProperty -Name relayMappings -Value @($newMappings) -Force

        if ($relayIsExisting) {
            $relay | Add-Member -MemberType NoteProperty -Name ExistingVM -Value $true -Force
            Add-ModifiedExistingVMToDeployConfig -VM $relay -ConfigToModify $Config -Hidden:$true
        }
        else {
            $configuredRelay = $Config.virtualMachines | Where-Object { $_.vmName -eq $relay.vmName } | Select-Object -First 1
            $configuredRelay.relayMappings = @($newMappings)
        }

        $resolved = @(Get-OsdPxePathsForNetwork -Network $Network -Config $Config)
        if ($resolved.Count -ne 1 -or $resolved[0].mode -ne 'Relay' -or
            $resolved[0].distributionPointVM -ne $target.VM.vmName) {
            $why = @($resolved | ForEach-Object { "$($_.mode): $($_.reason)" }) -join '; '
            throw "the saved mapping did not resolve to Relay ($why)"
        }

        # Keep the interactive existing-machine cache in sync only after the
        # hidden snapshot and resolver both succeeded.
        $sourceRelay = $global:existingMachines | Where-Object { $_.vmName -eq $relay.vmName } | Select-Object -First 1
        if ($sourceRelay) { $sourceRelay | Add-Member -MemberType NoteProperty -Name relayMappings -Value @($newMappings) -Force }
        Write-Log "Configured OSD PXE relay: $Network -> $($relay.vmName) -> $($target.VM.vmName) ($($target.SiteCode), $($target.IPv4))." -Success
        return $true
    }
    catch {
        $Config.virtualMachines = @($originalVirtualMachines)
        Write-RedX "Could not configure the DHCP relay for ${Network}: $($_.Exception.Message)"
        return $false
    }
}

function Resolve-OsdPxePathForNetwork {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)] [string] $Network,
        [Parameter(Mandatory = $true)] [object] $Config
    )

    while ($true) {
        $relayCandidates = @(Get-OsdRelayDistributionPointCandidates -Network $Network -Config $Config)
        $additionalOptions = [ordered]@{
            'D'  = "Install or enable a Distribution Point on $Network"
            'HD' = 'Uses the existing DP promotion and DP-only VM workflow'
        }
        if ($relayCandidates.Count -gt 0) {
            $additionalOptions['R'] = 'Relay PXE to an existing remote Distribution Point'
            $additionalOptions['HR'] = 'Uses one dedicated Ubuntu relay VM; Windows DHCP remains on the host'
        }
        $additionalOptions['B'] = 'Choose a different subnet'
        $additionalOptions['HB'] = 'Returns without changing the current PXE topology'

        $selection = Get-Menu2 -MenuName "OSD requires a PXE path on $Network" `
            -Prompt 'Choose a local Distribution Point, a remote relay target, or go back' `
            -OptionArray @() -AdditionalOptions $additionalOptions -Test:$false -Split
        if ([string]::IsNullOrWhiteSpace($selection) -or $selection -in @('B', 'ESCAPE')) { return $false }
        if ($selection -eq 'D' -and (Add-DistributionPointForOsdNetwork -Network $Network -Config $Config)) { return $true }
        if ($selection -eq 'R' -and (Add-DhcpRelayForOsdNetwork -Network $Network -Config $Config)) { return $true }
    }
}

function Get-OsdDistributionPointPromotionCandidates {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [string] $Network,
        [Parameter(Mandatory = $true)]
        [object] $Config
    )

    $sources = @(
        [pscustomobject]@{ VMs = @($Config.virtualMachines | Where-Object { -not $_.hidden }); TrackChanges = $false }
        [pscustomobject]@{ VMs = @($global:existingMachines); TrackChanges = $true }
    )
    $seen = @{}

    foreach ($source in $sources) {
        foreach ($candidate in $source.VMs) {
            $vmName = "$($candidate.vmName)"
            if (-not $vmName) { continue }
            $key = $vmName.ToLowerInvariant()
            if ($seen.ContainsKey($key)) { continue }
            $seen[$key] = $true

            if ((Get-OsdEffectiveNetwork -VM $candidate -Config $Config) -ne $Network) { continue }
            if ($candidate.role -notin @('DomainMember', 'SiteSystem')) { continue }
            if ($candidate.installDP -eq $true -or $candidate.enablePullDP -eq $true) { continue }
            if ($candidate.sqlVersion -or $candidate.remoteSQLVM) { continue }

            $operatingSystem = "$($candidate.operatingSystem)"
            if ($operatingSystem -notlike 'Server *' -and $operatingSystem -notlike 'Windows 11*') { continue }

            [pscustomobject]@{
                VM           = $candidate
                TrackChanges = [bool]$source.TrackChanges
            }
        }
    }
}

function Select-OsdDistributionPointSiteCode {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [string] $Network,
        [Parameter(Mandatory = $true)]
        [object] $Config,
        [Parameter(Mandatory = $false)]
        [object] $CandidateVM
    )

    $domain = "$($Config.vmOptions.domainName)"
    $sites = @(Get-EligiblePushSites -Config $Config -Domain $domain)
    if ($sites.Count -eq 0) {
        Write-RedX "A Distribution Point cannot be added because no Primary or Secondary site is available."
        return $null
    }

    $validSiteCodes = @($sites | ForEach-Object { "$($_.SiteCode)" })
    $lockedSiteCode = Get-PushClientSubnetLock -Subnet $Network -Config $Config -Domain $domain -DefaultNet $Config.vmOptions.network
    if (-not ($lockedSiteCode -and $validSiteCodes -contains "$lockedSiteCode")) { $lockedSiteCode = $null }

    $allVMs = @(Get-List2 -DeployConfig $Config)
    $allVMs += @($Config.virtualMachines | Where-Object { $_.hidden })
    if ($global:existingMachines) { $allVMs += @($global:existingMachines) }
    $assignedSiteCodes = @($allVMs | Where-Object {
            (Get-OsdEffectiveNetwork -VM $_ -Config $Config) -eq $Network -and
            ($_.pushClient -is [string]) -and $_.pushClient -and
            $validSiteCodes -contains "$($_.pushClient)"
        } | ForEach-Object { "$($_.pushClient)" } | Select-Object -Unique)
    if ($assignedSiteCodes.Count -gt 1) {
        Write-RedX "Subnet $Network has conflicting site assignments: $($assignedSiteCodes -join ', '). Resolve them before adding an OSD Distribution Point."
        return $null
    }

    $requiredSiteCode = $lockedSiteCode
    if ($assignedSiteCodes.Count -eq 1) {
        if ($requiredSiteCode -and $requiredSiteCode -ne $assignedSiteCodes[0]) {
            Write-RedX "Subnet $Network is owned by site $requiredSiteCode but contains a VM assigned to site $($assignedSiteCodes[0]). Resolve the conflict before adding an OSD Distribution Point."
            return $null
        }
        $requiredSiteCode = $assignedSiteCodes[0]
    }

    if ($CandidateVM -and $CandidateVM.role -eq 'SiteSystem' -and
        $CandidateVM.siteCode -and $validSiteCodes -contains "$($CandidateVM.siteCode)") {
        if ($requiredSiteCode -and $requiredSiteCode -ne "$($CandidateVM.siteCode)") {
            Write-RedX "SiteSystem '$($CandidateVM.vmName)' belongs to site $($CandidateVM.siteCode), but subnet $Network belongs to site $requiredSiteCode. Choose a different VM or create a new DP."
            return $null
        }
        return "$($CandidateVM.siteCode)"
    }
    if ($requiredSiteCode) {
        return "$requiredSiteCode"
    }

    $currentSiteCode = $null
    if ($CandidateVM) {
        foreach ($preferred in @($CandidateVM.siteCode, $CandidateVM.pushClient)) {
            if ($preferred -and ($validSiteCodes -contains "$preferred")) {
                $currentSiteCode = "$preferred"
                break
            }
        }
    }
    if (-not $currentSiteCode) {
        $matchingSite = $sites | Where-Object { $_.Network -eq $Network } | Select-Object -First 1
        if ($matchingSite) { $currentSiteCode = "$($matchingSite.SiteCode)" }
    }
    if (-not $currentSiteCode) {
        $currentSiteCode = "$((@($sites | Where-Object { $_.Role -eq 'Primary' }) + @($sites))[0].SiteCode)"
    }
    if ($sites.Count -eq 1) {
        return "$($sites[0].SiteCode)"
    }

    $siteOptions = @($sites | ForEach-Object { "$($_.SiteCode) [$($_.Role), $($_.Network)]" })
    $currentOption = $siteOptions | Where-Object { $_ -like "$currentSiteCode *" } | Select-Object -First 1
    if (-not $currentOption) { $currentOption = $currentSiteCode }
    $selection = Get-Menu2 -MenuName "Select the site that will own the DP on $Network" -Prompt "Select Primary or Secondary site" `
        -OptionArray $siteOptions -CurrentValue $currentOption -Test:$false -Split
    if ([string]::IsNullOrWhiteSpace($selection) -or $selection -eq 'ESCAPE') {
        return $null
    }
    return "$selection".Split(' ')[0]
}

function Set-OsdDistributionPointPromotionProperty {
    param (
        [Parameter(Mandatory = $true)]
        [object] $VM,
        [Parameter(Mandatory = $true)]
        [string] $Name,
        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [object] $Value,
        [Parameter(Mandatory = $true)]
        [bool] $TrackChanges
    )

    $hasProperty = $VM.PSObject.Properties.Name -contains $Name
    if ($hasProperty -and $VM.$Name -eq $Value) { return }

    if ($TrackChanges) {
        $originalName = "$Name-Original"
        if ($VM.PSObject.Properties.Name -notcontains $originalName) {
            $originalValue = if ($hasProperty) { $VM.$Name } else { $null }
            $VM | Add-Member -MemberType NoteProperty -Name $originalName -Value $originalValue -Force
        }
    }
    $VM | Add-Member -MemberType NoteProperty -Name $Name -Value $Value -Force
}

function Enable-OsdDistributionPointOnCandidate {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [object] $Candidate,
        [Parameter(Mandatory = $true)]
        [string] $SiteCode,
        [Parameter(Mandatory = $true)]
        [object] $Config
    )

    $sourceVM = $Candidate.VM
    $trackChanges = [bool]$Candidate.TrackChanges
    $vm = $sourceVM
    if ($trackChanges) {
        $vm = $sourceVM | ConvertTo-Json -Depth 5 | ConvertFrom-Json
    }
    $previousRole = "$($vm.role)"
    if ($trackChanges -and $vm.PSObject.Properties.Name -notcontains 'ExistingVM') {
        $vm | Add-Member -MemberType NoteProperty -Name ExistingVM -Value $true -Force
    }

    Set-OsdDistributionPointPromotionProperty -VM $vm -Name role -Value 'SiteSystem' -TrackChanges:$trackChanges
    Set-OsdDistributionPointPromotionProperty -VM $vm -Name siteCode -Value $SiteCode -TrackChanges:$trackChanges
    Set-OsdDistributionPointPromotionProperty -VM $vm -Name installDP -Value $true -TrackChanges:$trackChanges
    Set-OsdDistributionPointPromotionProperty -VM $vm -Name enablePullDP -Value $false -TrackChanges:$trackChanges

    if ($previousRole -eq 'DomainMember') {
        foreach ($roleProperty in @('installMP', 'installSUP', 'installRP', 'installSMSProv')) {
            Set-OsdDistributionPointPromotionProperty -VM $vm -Name $roleProperty -Value $false -TrackChanges:$trackChanges
        }
    }
    Set-SiteSystemPropertiesForOperatingSystem -VirtualMachine $vm

    if ($trackChanges) {
        $null = Add-ModifiedExistingVMToDeployConfig -VM $vm -ConfigToModify $Config -Hidden:$true
        if (-not ($Config.virtualMachines | Where-Object { $_.vmName -eq $vm.vmName -and $_.hidden })) {
            Write-RedX "Could not persist the Distribution Point changes for deployed VM '$($vm.vmName)'."
            return $null
        }

        foreach ($propertyName in @($sourceVM.PSObject.Properties.Name)) {
            if ($vm.PSObject.Properties.Name -notcontains $propertyName) {
                $sourceVM.PSObject.Properties.Remove($propertyName)
            }
        }
        foreach ($property in $vm.PSObject.Properties) {
            $sourceVM | Add-Member -MemberType NoteProperty -Name $property.Name -Value $property.Value -Force
        }
        $vm = $sourceVM
    }
    return $vm
}

function Add-DistributionPointForOsdNetwork {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [string] $Network,
        [Parameter(Mandatory = $true)]
        [object] $Config
    )

    while ($true) {
        $candidates = @(Get-OsdDistributionPointPromotionCandidates -Network $Network -Config $Config)
        $candidateOptions = @($candidates | ForEach-Object {
                $source = if ($_.TrackChanges) { 'deployed' } else { 'new' }
                "$($_.VM.vmName) [$source $($_.VM.role), $($_.VM.operatingSystem)]"
            })
        $additionalOptions = [ordered]@{
            'N'  = "Create a new Distribution Point VM on $Network"
            'HN' = 'Adds a DP-only SiteSystem VM on the selected subnet'
            'B'  = 'Choose a different subnet'
            'HB' = 'Returns to the OSDClient subnet picker without making changes'
        }

        $selection = Get-Menu2 -MenuName "OSD requires a Distribution Point on $Network" `
            -Prompt 'Select an existing VM for the DP role, create a new DP VM, or go back' `
            -OptionArray $candidateOptions -AdditionalOptions $additionalOptions -Test:$false -Split
        if ([string]::IsNullOrWhiteSpace($selection) -or $selection -in @('B', 'ESCAPE')) {
            return $false
        }

        if ($selection -eq 'N') {
            $siteCode = Select-OsdDistributionPointSiteCode -Network $Network -Config $Config
            if (-not $siteCode) { continue }

            $machineName = Add-NewVMForRole -Role 'SiteSystem' -Domain $Config.vmOptions.domainName `
                -ConfigToModify $Config -SiteCode $siteCode -Network $Network -ReturnMachineName:$true -DistributionPointOnly:$true
            $newDP = $Config.virtualMachines | Where-Object { $_.vmName -eq $machineName } | Select-Object -First 1
            if (-not $newDP) {
                Write-RedX "The new Distribution Point VM was not added. Choose another option."
                continue
            }
            $newDP.installDP = $true
            $newDP | Add-Member -MemberType NoteProperty -Name enablePullDP -Value $false -Force
            if ($newDP.PSObject.Properties.Name -contains 'installMP') { $newDP.installMP = $false }
            Set-SiteSystemPropertiesForOperatingSystem -VirtualMachine $newDP
            Write-Log "Added Distribution Point VM '$($newDP.vmName)' on $Network for site $siteCode." -Success
            return $true
        }

        $candidate = $candidates | Where-Object { $_.VM.vmName -eq $selection } | Select-Object -First 1
        if (-not $candidate) { continue }
        $siteCode = Select-OsdDistributionPointSiteCode -Network $Network -Config $Config -CandidateVM $candidate.VM
        if (-not $siteCode) { continue }

        $promotedVM = Enable-OsdDistributionPointOnCandidate -Candidate $candidate -SiteCode $siteCode -Config $Config
        if (-not $promotedVM) { continue }
        Write-Log "Enabled the Distribution Point role on '$($promotedVM.vmName)' on $Network for site $siteCode." -Success
        return $true
    }
}

function Select-OsdClientNetwork {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [object] $VM,
        [Parameter(Mandatory = $true)]
        [object] $Config
    )

    $currentNetwork = Get-OsdEffectiveNetwork -VM $VM -Config $Config
    while ($true) {
        $network = Select-Subnet -ConfigToCheck $Config -CurrentNetworkIsValid:$true -CurrentVM $VM
        if ([string]::IsNullOrWhiteSpace($network)) { return $currentNetwork }

        $allVMs = @(Get-List2 -DeployConfig $Config)
        $allVMs += @($Config.virtualMachines | Where-Object { $_.hidden })
        if ($global:existingMachines) { $allVMs += @($global:existingMachines) }
        $hasCmSite = @($allVMs | Where-Object { $_.role -in @('CAS', 'Primary', 'Secondary') }).Count -gt 0
        if (-not $hasCmSite) { return $network }

        if (Test-OsdNetworkHasDistributionPoint -Network $network -Config $Config) {
            return $network
        }
        $existingPath = @(Get-OsdPxePathsForNetwork -Network $network -Config $Config)
        if ($existingPath.Count -eq 1 -and $existingPath[0].mode -eq 'Relay') {
            Write-Log "Using stored OSD PXE relay: $network -> $($existingPath[0].relayVM) -> $($existingPath[0].distributionPointVM)." -Success
            return $network
        }
        if (Resolve-OsdPxePathForNetwork -Network $network -Config $Config) {
            return $network
        }
    }
}


function Get-NetworkForVM {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true, HelpMessage = "VM Object")]
        [object] $vm,
        [Parameter(Mandatory = $false, HelpMessage = "Config to Modify")]
        [object] $ConfigToModify = $global:config,
        [Parameter(Mandatory = $false, HelpMessage = "If a new network isn't needed, return null")]
        [bool] $ReturnIfNotNeeded = $false
    )

    $currentNetwork = $ConfigToModify.vmOptions.Network
    if ($currentNetwork -eq "10.234.241.0") {
        return
    }
    if ($vm.Network) {
        $currentNetwork = $vm.Network
    }
    $SiteServers = get-list2 -deployConfig $ConfigToModify | Where-Object { ($_.Role -eq "Primary" -or $_.Role -eq "Secondary") -and $_.vmName -ne $vm.vmName }
    #$SiteServers | convertto-Json | Out-Host
    #$ConfigToModify  |convertto-Json | Out-Host
    #$Secondaries = get-list2 -deployConfig $ConfigToModify  | Where-Object {$_.Role -eq "Secondary"}
    switch ($vm.role) {
        "Secondary" {
            if ($currentNetwork -in $SiteServers.network) {
                #Write-host "$CurrentNetwork is in $($SiteServers.network)"

                return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$false -CurrentVM $vm
            }
            else {
                if (-not $ReturnIfNotNeeded) {
                    return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$true -CurrentVM $vm
                }
            }
        }
        "Primary" {
            if ($currentNetwork -in $SiteServers.network) {
                #Write-host "$CurrentNetwork is in $($SiteServers.network)"

                return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$false -CurrentVM $vm
            }
            else {
                if (-not $ReturnIfNotNeeded) {
                    return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$true -CurrentVM $vm
                }
            }
        }
        "CAS" {
            $SiteServers = get-list2 -deployConfig $ConfigToModify | Where-Object { ($_.Role -eq "Primary" -or $_.Role -eq "Secondary" -or $_.Role -eq "CAS") -and $_.vmName -ne $vm.vmName }
            $SiteServers = $SiteServers | Where-Object { -not ($_.Role -eq "Primary" -and $_.ParentSiteCode -eq $vm.SiteCode) }
            if ($currentNetwork -in $SiteServers.network) {
                #Write-host "$CurrentNetwork is in $($SiteServers.network)"

                return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$false -CurrentVM $vm
            }
            else {
                if (-not $ReturnIfNotNeeded) {
                    return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$true -CurrentVM $vm
                }
            }
        }
        "PassiveSite" {
            $SS = Get-SiteServerForSiteCode -siteCode $vm.SiteCode -deployConfig $ConfigToModify -type VM
            if ($ss.network -ne $currentNetwork) {
                return $ss.Network
            }
        }
        "SiteSystem" {
            # Interactive edits must allow deliberate remote-DP placement. Creation
            # uses ReturnIfNotNeeded to inherit the site server's subnet by default.
            if (-not $ReturnIfNotNeeded) {
                return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$true -CurrentVM $vm
            }

            # sitesAndNetworks maps exactly one subnet per site code, so a DP/MP left
            # on the default network sits inside another site's boundary.
            # Get-SiteServerForSiteCode throws when the site code resolves to nothing.
            try {
                $SS = Get-SiteServerForSiteCode -siteCode $vm.SiteCode -deployConfig $ConfigToModify -type VM
            }
            catch {
                Write-Log "Get-NetworkForVM: no site server found for site code '$($vm.SiteCode)'; leaving $($vm.vmName) on $currentNetwork." -LogOnly
                return $null
            }
            if ($ss.network -ne $currentNetwork) {
                return $ss.Network
            }
        }
        Default {
            if (-not $ReturnIfNotNeeded) {
                if ($vm.role -eq 'OSDClient') {
                    return Select-OsdClientNetwork -VM $vm -Config $ConfigToModify
                }
                return Select-Subnet -config $configToModify -CurrentNetworkIsValid:$true -CurrentVM $vm

            }
        }
    }

    return $null
}

